/**
 * Finds a FossaPay bank by code or case-insensitive fuzzy name match.
 */
export function findFossaPayBank(query: string): FossaPayBank | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  
  // Exact code match
  const byCode = FossaPayBanks.find((b) => b.code.toLowerCase() === q);
  if (byCode) return byCode;

  // Exact name match
  const byExactName = FossaPayBanks.find((b) => b.name.toLowerCase() === q);
  if (byExactName) return byExactName;

  // Contains match
  return FossaPayBanks.find((b) => b.name.toLowerCase().includes(q) || q.includes(b.name.toLowerCase()));
}
