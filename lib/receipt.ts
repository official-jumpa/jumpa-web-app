/**
 * Receipt export. Three formats, no dependency: the image is drawn on a
 * canvas, the PDF is written by hand around that same drawing, and the CSV
 * is plain text.
 *
 * Everything here runs in the browser — it reads the app's own design tokens
 * off the document so an exported receipt can never drift from the screen.
 */

import {
  fontStack,
  loadImage,
  roundedRect,
  cssToken as token,
  wrapToWidth,
} from "@/lib/canvas";

export type ReceiptRow = {
  label: string;
  value: string;
  /** Printed in the brand colour, as the screen draws a link. */
  accent?: boolean;
};

export type Receipt = {
  /** File-name stem and the reference printed on the receipt. */
  reference: string;
  /** Headline outcome, e.g. "Payment Successful". */
  title: string;
  /** The figure, already formatted. */
  amount: string;
  status: string;
  timestamp: string;
  /** Caption in the pill above the rows; falls back to the title. */
  label?: string;
  /** Same-origin image for the pill's disc. */
  mark?: string | null;
  /** Picks the hero art; a receipt without one is a completed payment. */
  outcome?: "completed" | "pending" | "failed";
  rows: ReceiptRow[];
};

export type ReceiptFormat = "png" | "pdf" | "csv";

const MIME: Record<ReceiptFormat, string> = {
  png: "image/png",
  pdf: "application/pdf",
  csv: "text/csv;charset=utf-8",
};

const BRAND = "Jumpa";
const FOOTER = "Generated by Jumpa. Keep this for your records.";

export function receiptFilename(
  receipt: Receipt,
  format: ReceiptFormat,
): string {
  const stem = receipt.reference
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `jumpa-receipt-${stem || "transaction"}.${format}`;
}

/* ------------------------------------------------------------------ CSV -- */

/** RFC 4180: quote every field, double any quote inside it. */
function csvCell(value: string): string {
  return `"${value.replace(/"/g, '""')}"`;
}

function toCsv(receipt: Receipt): Blob {
  const lines = [
    ["Field", "Value"],
    ["Reference", receipt.reference],
    ["Status", receipt.status],
    ["Amount", receipt.amount],
    ["Date", receipt.timestamp],
    ...receipt.rows.map((row) => [row.label, row.value]),
  ].map((cells) => cells.map(csvCell).join(","));

  // The BOM is what makes Excel read UTF-8 rather than the system code page.
  return new Blob([`﻿${lines.join("\r\n")}\r\n`], { type: MIME.csv });
}

/* ---------------------------------------------------------- PNG + PDF -- */

/*
 * Both formats are one drawing of the on-screen receipt, laid out in CSS px
 * on the 393px frame and rendered at 3x. The PDF carries that drawing as a
 * JPEG page, so the two can never disagree.
 */

const FRAME = 393;
const GUTTER = 18;
const SCALE = 3;
const CARD_W = FRAME - GUTTER * 2;
const ROW_H = 20;
const ROW_GAP = 12;
const ROW_LINE = 16;
const BAND_TOP = 10;
const BAND_BOTTOM = 9;

const ART = "/images/receipt";
const MARK_SRC = "/logo/mark/purple.png";
const MARK_W = 40;
const MARK_H = (MARK_W * 381) / 803;

const FAILED_COPY =
  "Something went wrong. Your funds have not been sent. Please try again or contact support if the issue persists.";

/** Confetti around the failed rings: file, size, centre offset from the hero top, turn. */
const CONFETTI = [
  {
    src: "confetti-1",
    w: 14.0073,
    h: 14.2931,
    x: -80.5 + 7.22,
    y: 42 + 7.08,
    turn: 89.39,
  },
  { src: "confetti-2", w: 24.5, h: 25, x: 51.5 + 12.25, y: 78 + 12.5, turn: 0 },
  {
    src: "confetti-3",
    w: 18.3943,
    h: 18.7697,
    x: -61.5 + 11.45,
    y: 90 + 11.31,
    turn: -75,
  },
  { src: "confetti-4", w: 17, h: 20, x: 60.5 + 8.5, y: 20 + 10, turn: 0 },
] as const;

type Art = Record<string, HTMLImageElement | null>;

/** Every image the drawing uses, decoded before anything is drawn. */
async function loadArt(receipt: Receipt): Promise<Art> {
  const sources: Record<string, string> = {
    logo: MARK_SRC,
    band: `${ART}/band.svg`,
    medallion: `${ART}/medallion.svg`,
    dotGreen: `${ART}/dot-green.svg`,
    dotPurple: `${ART}/dot-purple.svg`,
    ring1: `${ART}/failed-ring-1.svg`,
    ring2: `${ART}/failed-ring-2.svg`,
    ring3: `${ART}/failed-ring-3.svg`,
    cross: `${ART}/failed-x.svg`,
  };
  for (const piece of CONFETTI) sources[piece.src] = `${ART}/${piece.src}.svg`;
  // Only same-origin marks; anything else would taint the canvas.
  if (receipt.mark?.startsWith("/")) sources.mark = receipt.mark;

  const entries = await Promise.all(
    Object.entries(sources).map(async ([key, src]) => [
      key,
      await loadImage(src).catch(() => null),
    ]),
  );
  return Object.fromEntries(entries);
}

type Palette = Record<
  "ink" | "white" | "brand" | "muted" | "label" | "line" | "rule",
  string
>;

function palette(): Palette {
  return {
    ink: token("black", "#000000"),
    white: token("white", "#ffffff"),
    brand: token("primary-600", "#8f12ff"),
    muted: token("grey-500", "#6b7381"),
    label: token("slate-600", "#545367"),
    line: token("surface-faq", "#f6f1ff"),
    rule: token("neutral-75", "#f4f4f4"),
  };
}

type Measured = {
  label: string;
  lines: string[];
  accent: boolean;
  height: number;
};

/** The hero's height, so the canvas can be sized before it is drawn. */
function heroHeight(outcome: Receipt["outcome"], failedLines: number): number {
  if (outcome === "failed") return 114 + 30 + 20 + 20 + failedLines * 15;
  if (outcome === "pending") return 30 + 9 + 20;
  return 139 + 30 + 9 + 20;
}

/** Draws the receipt as the detail screen shows it. Rejects if the canvas is refused. */
async function drawReceipt(receipt: Receipt): Promise<HTMLCanvasElement> {
  const art = await loadArt(receipt);
  const outcome = receipt.outcome ?? "completed";
  const family = fontStack();
  const colour = palette();

  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("Canvas is unavailable");

  const font = (weight: number, size: number, tracking = 0) => {
    ctx.font = `${weight} ${size}px ${family}`;
    ctx.letterSpacing = `${tracking}px`;
  };

  // Measure first: sizing the canvas resets the context.
  font(400, 12, -0.36);
  const labelWidth = (text: string) => ctx.measureText(text).width;
  font(600, 12);
  const measured: Measured[] = receipt.rows.map((row) => {
    const room = CARD_W - 24 - 10 - labelWidth(row.label) - 12;
    const lines = wrapToWidth(
      row.value,
      room,
      (text) => ctx.measureText(text).width,
    );
    return {
      label: row.label,
      lines,
      accent: Boolean(row.accent),
      height: ROW_H + (lines.length - 1) * ROW_LINE,
    };
  });
  font(400, 12);
  const failedLines = wrapToWidth(
    FAILED_COPY,
    230,
    (text) => ctx.measureText(text).width,
  );

  const heroTop = 72;
  const heroBottom = heroTop + heroHeight(outcome, failedLines.length);
  const bandTop = heroBottom + (outcome === "failed" ? 8 : 29);
  const pillTop = bandTop + BAND_TOP + 13;
  const cardTop = pillTop + 33 + 7;
  const rowsHeight =
    measured.reduce((total, row) => total + row.height, 0) +
    Math.max(measured.length - 1, 0) * ROW_GAP;
  const cardHeight = measured.length ? 17 + rowsHeight + 16 : 0;
  const bandBottom =
    (measured.length ? cardTop + cardHeight : pillTop + 33) + 23 + BAND_BOTTOM;
  const height = Math.ceil(bandBottom + 64);

  canvas.width = FRAME * SCALE;
  canvas.height = height * SCALE;
  ctx.scale(SCALE, SCALE);
  ctx.textBaseline = "middle";

  ctx.fillStyle = colour.white;
  ctx.fillRect(0, 0, FRAME, height);

  if (art.logo)
    ctx.drawImage(art.logo, FRAME - GUTTER - MARK_W, 30, MARK_W, MARK_H);

  const centre = FRAME / 2;
  ctx.textAlign = "center";

  if (outcome === "failed") {
    const cy = heroTop + 57;
    for (const [key, size] of [
      ["ring1", 114],
      ["ring2", 83.7551],
      ["ring3", 54.6685],
      ["cross", 16],
    ] as const) {
      const image = art[key];
      if (image)
        ctx.drawImage(image, centre - size / 2, cy - size / 2, size, size);
    }
    for (const piece of CONFETTI) {
      const image = art[piece.src];
      if (!image) continue;
      ctx.save();
      ctx.translate(centre + piece.x, heroTop + piece.y);
      ctx.rotate((piece.turn * Math.PI) / 180);
      ctx.drawImage(image, -piece.w / 2, -piece.h / 2, piece.w, piece.h);
      ctx.restore();
    }
    font(600, 20, -0.6);
    ctx.fillStyle = colour.ink;
    ctx.fillText("Transaction Failed", centre, heroTop + 114 + 30 + 10);
    font(400, 12);
    ctx.fillStyle = colour.label;
    failedLines.forEach((line, index) => {
      ctx.fillText(
        line,
        centre,
        heroTop + 114 + 30 + 20 + 20 + 7.5 + index * 15,
      );
    });
  } else {
    let textTop = heroTop;
    if (outcome === "completed") {
      const left = centre - 71;
      if (art.medallion)
        ctx.drawImage(art.medallion, left + 15, heroTop, 114, 114);
      if (art.dotGreen)
        ctx.drawImage(art.dotGreen, left + 131, heroTop + 35, 7, 7);
      if (art.dotPurple) ctx.drawImage(art.dotPurple, left, heroTop + 59, 7, 7);
      textTop = heroTop + 139;
    }
    font(600, 34, -0.85);
    ctx.fillStyle = colour.ink;
    ctx.fillText(receipt.amount, centre, textTop + 15, FRAME - GUTTER * 2);
    font(500, 14, -0.14);
    ctx.fillStyle = colour.muted;
    const status =
      outcome === "pending" ? "Transaction pending" : receipt.title;
    ctx.fillText(status, centre, textTop + 30 + 9 + 10);
  }

  // The band stretches between its notched top and bottom edges.
  if (art.band) {
    const middle = bandBottom - bandTop - BAND_TOP - BAND_BOTTOM;
    ctx.drawImage(art.band, 0, 0, 393, BAND_TOP, 0, bandTop, FRAME, BAND_TOP);
    ctx.drawImage(
      art.band,
      0,
      BAND_TOP,
      393,
      321 - BAND_TOP - BAND_BOTTOM,
      0,
      bandTop + BAND_TOP,
      FRAME,
      middle,
    );
    ctx.drawImage(
      art.band,
      0,
      321 - BAND_BOTTOM,
      393,
      BAND_BOTTOM,
      0,
      bandBottom - BAND_BOTTOM,
      FRAME,
      BAND_BOTTOM,
    );
  }

  const box = (y: number, h: number, radius: number) => {
    ctx.fillStyle = colour.white;
    roundedRect(ctx, GUTTER, y, CARD_W, h, radius);
    ctx.fill();
    ctx.strokeStyle = colour.line;
    ctx.lineWidth = 1;
    roundedRect(ctx, GUTTER + 0.5, y + 0.5, CARD_W - 1, h - 1, radius - 0.5);
    ctx.stroke();
  };

  box(pillTop, 33, 20);
  const pillMid = pillTop + 16.5;
  let labelX = GUTTER + 18;
  if (art.mark) {
    ctx.save();
    ctx.beginPath();
    ctx.arc(labelX + 10.5, pillMid, 10.5, 0, Math.PI * 2);
    ctx.clip();
    ctx.drawImage(art.mark, labelX, pillMid - 10.5, 21, 21);
    ctx.restore();
    labelX += 21 + 7;
  }
  font(400, 10, -0.3);
  ctx.fillStyle = colour.ink;
  ctx.textAlign = "left";
  ctx.fillText(receipt.label ?? receipt.title, labelX, pillMid);
  ctx.textAlign = "right";
  ctx.fillText(receipt.timestamp, GUTTER + CARD_W - 17, pillMid);

  if (measured.length) {
    box(cardTop, cardHeight, 24);
    const labelLeft = GUTTER + 12 + 8;
    const valueRight = GUTTER + CARD_W - 12 - 2;
    let y = cardTop + 17;
    measured.forEach((row, index) => {
      if (index > 0) {
        const rule = y - ROW_GAP / 2;
        ctx.strokeStyle = colour.rule;
        ctx.lineCap = "round";
        ctx.setLineDash([2.5, 7.5]);
        ctx.beginPath();
        ctx.moveTo(GUTTER + 12 + 7.5, rule);
        ctx.lineTo(GUTTER + 12 + 7 + 321.5, rule);
        ctx.stroke();
        ctx.setLineDash([]);
      }
      font(400, 12, -0.36);
      ctx.fillStyle = colour.label;
      ctx.textAlign = "left";
      ctx.fillText(row.label, labelLeft, y + ROW_H / 2);
      font(600, 12);
      ctx.fillStyle = row.accent ? colour.brand : colour.ink;
      ctx.textAlign = "right";
      row.lines.forEach((line, lineIndex) => {
        ctx.fillText(line, valueRight, y + ROW_H / 2 + lineIndex * ROW_LINE);
      });
      y += row.height + ROW_GAP;
    });
  }

  ctx.textAlign = "center";
  font(400, 10);
  ctx.fillStyle = colour.muted;
  ctx.fillText(`Reference: ${receipt.reference}`, centre, bandBottom + 24);
  ctx.fillText(FOOTER, centre, bandBottom + 40);

  return canvas;
}

async function toPng(receipt: Receipt): Promise<Blob> {
  const canvas = await drawReceipt(receipt);
  return new Promise((resolve, reject) => {
    canvas.toBlob(
      (blob) =>
        blob ? resolve(blob) : reject(new Error("Could not render the image")),
      MIME.png,
    );
  });
}

/** An image the PDF can carry, with its bytes held as a latin1 string. */
type PdfImage = { data: string; width: number; height: number };

/** One page the size of the receipt, in points, carrying the drawing as JPEG
 *  (PDF reads JPEG natively through DCTDecode). */
async function toPdf(receipt: Receipt): Promise<Blob> {
  const canvas = await drawReceipt(receipt);
  const url = canvas.toDataURL("image/jpeg", 0.92);
  // atob hands back exactly one character per byte.
  const image: PdfImage = {
    data: atob(url.slice(url.indexOf(",") + 1)),
    width: canvas.width,
    height: canvas.height,
  };
  const pageWidth = FRAME;
  const pageHeight = canvas.height / SCALE;
  // `cm` places the unit image square: width, height, then its bottom-left.
  const content = `q ${pageWidth} 0 0 ${pageHeight} 0 0 cm /Im0 Do Q`;
  return new Blob([assemblePdf(content, image, pageWidth, pageHeight)], {
    type: MIME.pdf,
  });
}

/**
 * Five objects, an xref table and a trailer: catalog, pages, page, content
 * and the receipt image.
 *
 * The file is built as a latin1 string, one character per byte, so a string
 * offset is the byte offset the xref table has to name even where the JPEG
 * runs outside ASCII.
 */
function assemblePdf(
  content: string,
  image: PdfImage,
  width: number,
  height: number,
): ArrayBuffer {
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${width} ${height}] ` +
      "/Resources << /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /XObject /Subtype /Image " +
      `/Width ${image.width} /Height ${image.height} ` +
      "/ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode " +
      `/Length ${image.data.length} >>\nstream\n${image.data}\nendstream`,
  ];

  let file = "%PDF-1.4\n";
  const offsets: number[] = [];

  objects.forEach((body, index) => {
    offsets.push(file.length);
    file += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xref = file.length;
  file += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    file += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  file +=
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n` +
    `startxref\n${xref}\n%%EOF\n`;

  return latin1(file);
}

/** One byte per character. Handing back the buffer rather than a view keeps
 *  `Blob` happy without a cast. */
function latin1(value: string): ArrayBuffer {
  const buffer = new ArrayBuffer(value.length);
  const bytes = new Uint8Array(buffer);
  for (let index = 0; index < value.length; index += 1) {
    bytes[index] = value.charCodeAt(index) & 0xff;
  }
  return buffer;
}

/* --------------------------------------------------------------- public -- */

export function buildReceipt(
  receipt: Receipt,
  format: ReceiptFormat,
): Promise<Blob> {
  if (format === "csv") return Promise.resolve(toCsv(receipt));
  if (format === "pdf") return toPdf(receipt);
  return toPng(receipt);
}

/** Saves a blob under `filename`, then hands the object URL back. */
export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  // Revoked on the next frame: Safari cancels the save if it goes immediately.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function canShareFiles(): boolean {
  return (
    typeof navigator !== "undefined" &&
    typeof navigator.canShare === "function" &&
    typeof navigator.share === "function"
  );
}

/** Hands the receipt to the OS share sheet. Returns false if it declined it. */
export async function shareReceipt(
  receipt: Receipt,
  format: ReceiptFormat = "png",
): Promise<boolean> {
  if (!canShareFiles()) return false;

  const blob = await buildReceipt(receipt, format);
  const file = new File([blob], receiptFilename(receipt, format), {
    type: blob.type,
  });
  if (!navigator.canShare({ files: [file] })) return false;

  await navigator.share({ files: [file], title: `${BRAND} receipt` });
  return true;
}

/**
 * A reference for a flow that has no provider id yet. Visibly ours, sortable,
 * and stable once stamped.
 */
export function newReference(prefix: string): string {
  const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  return `${prefix}-${stamp}`;
}
